export function getMonsterBuddy(id) {
  return (
    monsterBuddyRoster.find((buddy) => buddy.id === id) ||
    monsterBuddyRoster[0]
  );
}

export function getMonsterBuddyByIndex(index = 0) {
  const safeIndex =
    ((Number(index) || 0) % monsterBuddyRoster.length +
      monsterBuddyRoster.length) %
    monsterBuddyRoster.length;

  return monsterBuddyRoster[safeIndex];
}

export function pickMonsterBuddy(seed = "", offset = 0) {
  const score = [...String(seed)].reduce(
    (total, character) => total + character.charCodeAt(0),
    0,
  );

  return getMonsterBuddyByIndex(score + offset);
}
